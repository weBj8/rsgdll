//! Typed built-in hook markers (spec §10.4), generated from the vendored API database into
//! `crates/rsgdll-gmod/src/hooks_gen.rs`.

use rsgdll_apidb::{ApiDb, Hook, Realm};

/// Whether `class` is `base` or derives from it.
fn derives(db: &ApiDb, class: &str, base: &str) -> bool {
    std::iter::successors(Some(class.to_owned()), |c| {
        db.classes.get(c).cloned().flatten()
    })
    .take(16)
    .any(|c| c == base)
}

/// Snippet type -> argument type (borrowing `'a`).
pub fn arg_type(db: &ApiDb, ty: &str, optional: bool) -> String {
    let base = ty.split('|').next().unwrap_or(ty).trim_end_matches('?');
    let t = match base {
        "number" | "integer" => "f64".to_owned(),
        "string" => "String".to_owned(),
        "boolean" => "bool".to_owned(),
        "Vector" => "Vector".to_owned(),
        "Angle" => "Angle".to_owned(),
        "Color" => "Color".to_owned(),
        "table" | "TraceResult" => "LuaTable".to_owned(),
        c if derives(db, c, "Player") => return "Option<PlayerRef<'a>>".to_owned(),
        c if derives(db, c, "Entity") => return "Option<EntityRef<'a>>".to_owned(),
        _ => return "LuaValue".to_owned(),
    };
    if optional { format!("Option<{t}>") } else { t }
}

/// First return -> optional owned value (`nil` = no override).
pub fn ret_type(ret: Option<&String>) -> String {
    match ret.map(|r| r.split('|').next().unwrap_or(r).trim_end_matches('?')) {
        None => "Nil".to_owned(),
        Some("number" | "integer") => "Option<f64>".to_owned(),
        Some("string") => "Option<String>".to_owned(),
        Some("boolean") => "Option<bool>".to_owned(),
        Some(_) => "LuaValue".to_owned(),
    }
}

fn realm(r: Realm) -> &'static str {
    match r {
        Realm::Server => "Some(Realm::Server)",
        Realm::Client => "Some(Realm::Client)",
        Realm::Menu => "Some(Realm::Menu)",
        Realm::Shared => "None",
    }
}

fn marker(db: &ApiDb, h: &Hook) -> String {
    let params: Vec<_> = h.params.iter().filter(|p| p.name != "...").collect();
    let args = params
        .iter()
        .map(|p| arg_type(db, &p.ty, p.optional))
        .collect::<Vec<_>>();
    let names = params
        .iter()
        .map(|p| p.name.as_str())
        .collect::<Vec<_>>()
        .join(", ");
    let tuple = match args.len() {
        1 => format!("({},)", args[0]),
        _ => format!("({})", args.join(", ")),
    };
    format!(
        "/// {owner}:{name} ({realm}). Args: {names}.\npub struct {name};\nimpl Hook for {name} {{\n    const NAME: &'static str = \"{name}\";\n    const REALM: Option<Realm> = {r};\n    const ARITY: usize = {n};\n    type Args<'a> = {tuple};\n    type Ret = {ret};\n}}\n",
        owner = h.owner,
        name = h.name,
        realm = h.realm.as_str(),
        r = realm(h.realm),
        n = args.len(),
        ret = ret_type(h.returns.first()),
    )
}

pub fn generate(db: &ApiDb) -> String {
    let mut hooks: Vec<&Hook> = db
        .hooks
        .values()
        .filter(|h| {
            h.name
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '_')
        })
        .collect();
    hooks.sort_by(|a, b| (&a.owner, &a.name).cmp(&(&b.owner, &b.name)));
    let section = |owner: &str| {
        hooks
            .iter()
            .filter(|h| h.owner == owner)
            .map(|h| marker(db, h))
            .collect::<Vec<_>>()
            .join("\n")
    };
    format!(
        "// @generated by `cargo xtask gen-apidb`. Do not edit.\n#![allow(non_camel_case_types)]\n\nuse crate::hook::Hook;\nuse rsgdll_core::{{Realm, conv::*}};\n\n{}\n\n/// `SANDBOX:` hooks (only fire when the gamemode derives sandbox).\npub mod sandbox {{\n    use super::*;\n\n{}\n}}\n",
        section("GM"),
        section("SANDBOX")
            .lines()
            .map(|l| if l.is_empty() {
                String::new()
            } else {
                format!("    {l}")
            })
            .collect::<Vec<_>>()
            .join("\n")
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn maps_player_say() {
        let db = rsgdll_apidb::parse(
            "C\tPlayer\tEntity\nC\tEntity\t-\nH\tGM\tPlayerSay\tserver\tsender:Player,text:string,teamChat:boolean\tstring\n",
        );
        let out = generate(&db);
        assert!(
            out.contains("type Args<'a> = (Option<PlayerRef<'a>>, String, bool);"),
            "{out}"
        );
        assert!(out.contains("type Ret = Option<String>;"));
        assert!(out.contains("const REALM: Option<Realm> = Some(Realm::Server);"));
    }
}
